-- ============================================================
-- 国际四方支付 Dypay - 首次部署后置强化脚本
-- 文件：sql/post_install_hardening.sql
-- 用途：消除社区默认值的安全风险
-- 执行时机：仅在首次部署完成（init.sql + 所有补丁 + 服务正常启动后）执行一次
-- 重复执行：幂等（UPDATE 语句无副作用，但请勿改回旧值）
-- ============================================================
-- 为什么需要本脚本：
-- 1. init.sql 内置 admin 账号的 BCrypt 盐为公开仓库可见的 'testkey'，
--    攻击者拿到密文可基于已知盐做离线爆破，因此必须改盐 + 改密。
-- 2. 默认 admin 仅作首次登陆使用，运营必须立即在前台创建独立账号并禁用本号。
-- ============================================================

SET NAMES utf8mb4;

-- ------------------------------------------------------------
-- 1. 强制提示：执行前请确认已修改下面占位
-- ------------------------------------------------------------
-- BCrypt 密码生成参考（任选一种，本地执行不要走网络服务）：
--   Java:   org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder.encode("你的新密码")
--   Python: from bcrypt import hashpw, gensalt; hashpw(b"你的新密码", gensalt(10))
--   命令行: htpasswd -nbBC 10 "" "你的新密码" | tr -d ':\n' | sed 's/^\$2y/$2a/'
--
-- 把生成的密文替换下方 :NEW_BCRYPT_HASH，把新盐替换 :NEW_SALT（16-32 位随机字符串）。
-- 占位以 ':' 开头是判别特征，未替换时下方守卫会让脚本主动失败。
-- ------------------------------------------------------------

-- ------------------------------------------------------------
-- 2. 占位守卫（必须替换占位才能继续，否则触发 SQL 错误中止脚本）
-- ------------------------------------------------------------
-- 原理：1/0 在 MySQL 8 默认 sql_mode（含 ERROR_FOR_DIVISION_BY_ZERO）下会抛
--      ER_DIVIDE_BY_ZERO (1365)，mysql 客户端批处理模式会中断后续语句。
-- 仅当字面量仍以 ':' 开头（占位未替换）时触发；运维真实替换后跳过本守卫。
-- 配合下方 UPDATE 的 WHERE 占位条件，构成"双保险"。
SELECT
  CASE
    WHEN ':NEW_BCRYPT_HASH' LIKE ':%' OR ':NEW_SALT' LIKE ':%'
    THEN (1/0)  -- 触发 ER_DIVIDE_BY_ZERO 让脚本中断
    ELSE 1
  END AS placeholder_guard;

-- ------------------------------------------------------------
-- 3. 改 admin 账号密文 + 盐
-- ------------------------------------------------------------
-- WHERE 中再次校验占位未替换：守卫被绕过时（如 sql_mode 调整）仍能保护 admin 密码不被改成字面量。
UPDATE t_sys_user_auth
  SET credential = ':NEW_BCRYPT_HASH',
      salt       = ':NEW_SALT'
WHERE user_id = 801
  AND identity_type = '1'
  AND identifier = 'admin'
  AND ':NEW_BCRYPT_HASH' NOT LIKE ':%'   -- 占位未替换时本条 UPDATE 0 行受影响
  AND ':NEW_SALT'        NOT LIKE ':%';

-- ------------------------------------------------------------
-- 4. 验证：执行完成后查询应返回 1 行，且 salt != 'testkey'
-- ------------------------------------------------------------
SELECT user_id, identifier, salt,
       CASE WHEN salt = 'testkey' THEN '❌ 仍为社区默认盐，未生效'
            ELSE '✅ 已强化'
       END AS status
FROM t_sys_user_auth
WHERE user_id = 801;

